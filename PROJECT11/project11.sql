CREATE OR REPLACE TABLE STG_CUSTOMERS_INITIAL (
    CUSTOMER_ID   INT,
    CUSTOMER_NAME VARCHAR(100),
    CITY          VARCHAR(100),
    STATE         VARCHAR(100),
    MEMBERSHIP    VARCHAR(50),
    SEGMENT       VARCHAR(50)
);

CREATE OR REPLACE TABLE STG_CUSTOMER_UPDATES (
    CUSTOMER_ID    INT,
    CUSTOMER_NAME  VARCHAR(100),
    CITY           VARCHAR(100),
    STATE          VARCHAR(100),
    MEMBERSHIP     VARCHAR(50),
    SEGMENT        VARCHAR(50),
    EFFECTIVE_DATE DATE
);

COPY INTO STG_CUSTOMERS_INITIAL
