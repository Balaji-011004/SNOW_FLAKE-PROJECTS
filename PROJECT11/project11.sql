INSERT INTO DIM_CUSTOMER (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT 
    u.CUSTOMER_ID,
    u.CUSTOMER_NAME,
    u.CITY,
    d.CITY AS PREVIOUS_CITY,
    u.STATE,
    u.MEMBERSHIP AS CURRENT_MEMBERSHIP,
    d.HISTORICAL_MEMBERSHIP AS PREVIOUS_MEMBERSHIP,
    u.MEMBERSHIP AS HISTORICAL_MEMBERSHIP,
    u.SEGMENT,
    u.EFFECTIVE_DATE,
    '9999-12-31'::DATE AS EXPIRY_DATE,
    TRUE AS IS_CURRENT
FROM STG_CUSTOMER_UPDATES u
JOIN DIM_CUSTOMER d 
  ON u.CUSTOMER_ID = d.CUSTOMER_ID
WHERE d.EXPIRY_DATE = u.EFFECTIVE_DATE - 1;

---Synchronize global current & prior attributes across all records
UPDATE DIM_CUSTOMER d
SET 
    CITY = u.CITY,
    PREVIOUS_CITY = CASE WHEN d.CITY <> u.CITY THEN d.CITY ELSE d.PREVIOUS_CITY END,
    STATE = u.STATE,
    CURRENT_MEMBERSHIP = u.MEMBERSHIP,
    PREVIOUS_MEMBERSHIP = d.HISTORICAL_MEMBERSHIP
FROM STG_CUSTOMER_UPDATES u
WHERE d.CUSTOMER_ID = u.CUSTOMER_ID
AND u.CUSTOMER_ID = 101;

