CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY          INT AUTOINCREMENT START 1 INCREMENT 1,
    CUSTOMER_ID           INT,
    CUSTOMER_NAME         VARCHAR(100),
    CITY                  VARCHAR(100),
    PREVIOUS_CITY         VARCHAR(100),
    STATE                 VARCHAR(100),
    CURRENT_MEMBERSHIP    VARCHAR(50),
    PREVIOUS_MEMBERSHIP   VARCHAR(50),
    HISTORICAL_MEMBERSHIP VARCHAR(50),
    SEGMENT               VARCHAR(50),
    EFFECTIVE_DATE        DATE,
    EXPIRY_DATE           DATE,
    IS_CURRENT            BOOLEAN
);

INSERT INTO DIM_CUSTOMER (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
